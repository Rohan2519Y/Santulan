/*
 * Generates backend/migrations/018_santulan_seed_reference_content.sql (BUILD 01 §10 fail-closed seed) from the source
 * workbooks under docs/. Deterministic: same inputs => byte-identical output.
 *
 *   items            docs/Santulan 2.0/BUILD_02_.../Santulan_BUILD_02_Assessment_Catalog_and_Item_Audit_v3_1.xlsx
 *                    sheets 01_ASSESSMENT_CATALOG, 03_ADOL_CANONICAL, 04_EA_CANONICAL (the v3.1 canonical rows)
 *   actions/prompts  docs/Santulan_Development_Reporting_MASTER_System_v1_1.xlsx sheets 07_Development_Action_Library,
 *                    04_Subdomain_Master_Ref
 *
 * Assumptions recorded in the generated file (D-08, D-11): item_id is UUIDv5(versionId:itemCode); hashes are stored
 * verbatim from the workbook; the action library_version label and duration upper-bound are not stated by the contracts.
 */
const fs = require('fs');
const path = require('path');
const XLSX = require('xlsx');
const {
  DRM, ITEM_ID_NAMESPACE, SCALE_VERSION, SCALE_ANCHORS: scaleAnchors, SCALE_KEYING: scaleKeying, SCALE_HASH: scaleHash,
  q, rows, loadBuild02, uuidv5,
} = require('./lib/catalogSource');

const OUT = path.join(__dirname, '..', 'migrations', '018_santulan_seed_reference_content.sql');
const ACTION_LIBRARY_VERSION = 'DRM-v1.1'; // ASSUMED (D-11)

const { catalog, itemSets } = loadBuild02();

const drm = XLSX.readFile(DRM);
const actionRows = rows(drm, '07_Development_Action_Library').filter((r) => /^DAL-\d{3}$/.test(r['Action ID']));
const subRows = rows(drm, '04_Subdomain_Master_Ref').filter((r) => /^C\d/.test(r['Subdomain Code']));
if (actionRows.length !== 216) throw new Error(`expected 216 actions, found ${actionRows.length}`);
if (subRows.length !== 72) throw new Error(`expected 72 subdomain rows, found ${subRows.length}`);


const out = [];
out.push(`-- SanTulan 2.0 canonical schema — BUILD 01 v3.1 §10 seed contract (011: fail-closed v3.1 content seeds).
-- GENERATED by backend/scripts/santulan-generate-seed-sql.js — do not edit by hand; regenerate instead.
--
--   1 candidate response scale (DRAFT) · 2 assessment versions (DRAFT / CLOSED) · 175 + 171 items ·
--   216 development actions (active = false) · 72 reflection prompts (DRAFT) · 0 interpretation rules.
--
-- Sources: BUILD 02 workbook sheets 01_ASSESSMENT_CATALOG / 03_ADOL_CANONICAL / 04_EA_CANONICAL (v3.1 canonical rows:
-- Authenticity C4.4, Autonomy C4.5, C5 = C5.1-C5.7) and the Development Reporting Master v1.1 (actions, prompts).
-- ASSUMED (D-08): items.item_id = UUIDv5(assessment_version_id || ':' || item_code) under namespace ${ITEM_ID_NAMESPACE};
--   all hashes are stored verbatim from the workbook (not reproducible from the on-disk sources).
-- ASSUMED (D-11): development_actions.library_version = '${ACTION_LIBRARY_VERSION}'; duration_minutes = upper bound of the
--   stated range; the candidate response-scale content_hash is computed locally over its anchors and keying definition.
SET LOCAL search_path TO santulan, public;
`);

out.push(`INSERT INTO response_scales (version, scale_points, anchor_labels, keying_definition, content_hash, status)
VALUES (${q(SCALE_VERSION)}, 5, ${q(JSON.stringify(scaleAnchors))}::jsonb, ${q(JSON.stringify(scaleKeying))}::jsonb, ${q(scaleHash)}, 'DRAFT');
`);

out.push('INSERT INTO assessment_versions (assessment_version_id, version_label, configuration, participant_min_age, participant_max_age, response_scale_id, content_hash, source_file_hash, status, participation_state) VALUES');
out.push(catalog.map((c) => `  (${q(c.assessment_version_id)}, ${q(c.version_label)}, ${q(c.configuration)}, ${Number(c.participant_min_age)}, ${Number(c.participant_max_age)}, (SELECT response_scale_id FROM response_scales WHERE version = ${q(SCALE_VERSION)}), ${q(c.assessment_content_hash_build01)}, ${q(c.source_file_sha256)}, 'DRAFT', 'CLOSED')`).join(',\n') + ';\n');

const versionIdByLabel = Object.fromEntries(catalog.map((c) => [c.version_label, c.assessment_version_id]));
for (const [name, list] of Object.entries(itemSets)) {
  const label = list[0].version_label;
  const vid = versionIdByLabel[label];
  if (!vid) throw new Error(`no catalog row for ${label}`);
  out.push(`-- ${name}: ${list.length} items (${label})`);
  out.push('INSERT INTO items (item_id, assessment_version_id, item_code, domain_code, subdomain_code, subdomain_name, item_text, keying, age_band, context, layer, pilot_status, display_order, status, item_content_hash) VALUES');
  out.push(list.map((r) => {
    if (r.version_label !== label) throw new Error('mixed version labels');
    if (r.source_keying !== 'Positive' || r.keying !== 'POSITIVE') throw new Error(`unexpected keying on ${r.item_code}`);
    if (r.layer !== 'CORE') throw new Error(`non-CORE item ${r.item_code}`);
    return `  (${q(uuidv5(`${vid}:${r.item_code}`, ITEM_ID_NAMESPACE))}, ${q(vid)}, ${q(r.item_code)}, ${q(r.domain_code)}, ${q(r.subdomain_code)}, ${q(r.subdomain_name)}, ${q(r.item_text)}, 'POSITIVE', ${q(r.age_band)}, ${q(r.context)}, 'CORE', ${q(r.pilot_status)}, ${Number(r.display_order)}, 'ACTIVE', ${q(r.item_content_hash)})`;
  }).join(',\n') + ';\n');
}

// development actions: map DAL-### -> canonical subdomain through the Subdomain Master Ref action-id columns
const subByAction = {};
for (const s of subRows) {
  for (const k of ['Foundation Action ID', 'Practice Action ID', 'Transfer Action ID']) subByAction[s[k]] = s;
}
out.push('-- 216 development actions (72 subdomains x Foundation/Practice/Transfer), seeded INACTIVE');
out.push('INSERT INTO development_actions (action_code, library_version, domain_code, subdomain_code, progression_level, action_text, age_band, action_type, duration_minutes, practice_window, evidence_status, control_flags, active) VALUES');
out.push(actionRows.map((a) => {
  const s = subByAction[a['Action ID']];
  if (!s) throw new Error(`no subdomain for ${a['Action ID']}`);
  const m = a.Duration.match(/(\d+)\D+(\d+)/);
  const minutes = m ? Number(m[2]) : null;
  const flags = { control: a.Control, level: a.Level, process: a.Process, age_routing: a['Age Routing'], duration_text: a.Duration };
  return `  (${q(a['Action ID'])}, ${q(ACTION_LIBRARY_VERSION)}, ${q(s['Domain Code'])}, ${q(s['Subdomain Code'])}, ${q(a.Progression)}, ${q(a['Action Text'])}, ${q(a['Age Routing'].split(';')[0].trim())}, ${q(a['Action Type'])}, ${minutes === null ? 'NULL' : minutes}, ${q(a['Practice Window'])}, ${q(s['Evidence Status'])}, ${q(JSON.stringify(flags))}::jsonb, false)`;
}).join(',\n') + ';\n');

out.push('-- 72 reflection prompts (one current source prompt per canonical subdomain), seeded DRAFT');
out.push('INSERT INTO reflection_prompts (prompt_code, domain_code, subdomain_code, prompt_text, age_band, sequence, version, status) VALUES');
out.push(subRows.map((s) => `  (${q('RP-' + s['Subdomain Code'])}, ${q(s['Domain Code'])}, ${q(s['Subdomain Code'])}, ${q(s['Reflection Prompt'])}, '13–25', 1, ${q(ACTION_LIBRARY_VERSION)}, 'DRAFT')`).join(',\n') + ';\n');

out.push(`-- BUILD 01 §10.1 item-bank verification (fails the migration on any drift)
DO $$
DECLARE r record; n integer;
BEGIN
  SELECT count(*) INTO n FROM items i JOIN assessment_versions v USING (assessment_version_id) WHERE v.version_label = 'santulan-adolescent-pilot-v3.1';
  IF n <> 175 THEN RAISE EXCEPTION 'adolescent items: expected 175, found %', n; END IF;
  SELECT count(*) INTO n FROM items i JOIN assessment_versions v USING (assessment_version_id) WHERE v.version_label = 'santulan-emergingadult-pilot-v3.1';
  IF n <> 171 THEN RAISE EXCEPTION 'emerging-adult items: expected 171, found %', n; END IF;
  FOR r IN SELECT v.version_label, count(DISTINCT i.subdomain_code) AS s FROM items i JOIN assessment_versions v USING (assessment_version_id) GROUP BY 1 LOOP
    IF r.s <> 72 THEN RAISE EXCEPTION '% covers % subdomains, expected 72', r.version_label, r.s; END IF;
  END LOOP;
  SELECT count(*) INTO n FROM items a JOIN items b ON a.item_code = b.item_code AND a.assessment_version_id <> b.assessment_version_id
    WHERE a.assessment_version_id = 'd6c8be95-0290-5aad-8ab8-f20e3a786e13' AND a.item_text = b.item_text AND a.subdomain_code = b.subdomain_code;
  IF n <> 124 THEN RAISE EXCEPTION 'shared item codes: expected 124 with identical text/subdomain, found %', n; END IF;
  IF EXISTS (SELECT 1 FROM items WHERE subdomain_code = 'C4.6' OR (domain_code = 'C5' AND subdomain_code NOT LIKE 'C5.%')) THEN
    RAISE EXCEPTION 'legacy construct codes found';
  END IF;
  SELECT count(*) INTO n FROM development_actions WHERE active; IF n <> 0 THEN RAISE EXCEPTION 'actions must be seeded inactive'; END IF;
  SELECT count(*) INTO n FROM development_actions; IF n <> 216 THEN RAISE EXCEPTION 'expected 216 actions, found %', n; END IF;
  SELECT count(*) INTO n FROM reflection_prompts; IF n <> 72 THEN RAISE EXCEPTION 'expected 72 prompts, found %', n; END IF;
  SELECT count(*) INTO n FROM interpretation_rules; IF n <> 0 THEN RAISE EXCEPTION 'no interpretation rules may be seeded'; END IF;
  SELECT count(*) INTO n FROM assessment_versions WHERE status <> 'DRAFT' OR participation_state <> 'CLOSED'; IF n <> 0 THEN RAISE EXCEPTION 'versions must seed DRAFT/CLOSED'; END IF;
END $$;`);

fs.writeFileSync(OUT, out.join('\n') + '\n', 'utf8');
console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${fs.statSync(OUT).size} bytes)`); // eslint-disable-line no-console
